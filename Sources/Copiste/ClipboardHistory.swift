import AppKit

/// Image copiée (PNG), gardée dans l'historique.
struct ClipImage: Identifiable, Hashable {
    let id = UUID()
    let png: Data

    var image: NSImage? { NSImage(data: png) }
    var pixelSize: NSSize? {
        guard let rep = NSBitmapImageRep(data: png) else { return nil }
        return NSSize(width: rep.pixelsWide, height: rep.pixelsHigh)
    }
}

/// Historique du presse-papier : textes et images, en mémoire.
/// Sur disque : les épinglés (pins.json) et, seulement si l'utilisateur l'active,
/// l'historique complet chiffré (history.enc, clé dans le Trousseau).
/// macOS ne notifie pas les changements : on compare `changeCount` toutes les 0,5 s.
final class ClipboardHistory {
    static let persistKey = "persistHistory"
    static var persistEnabled: Bool { UserDefaults.standard.bool(forKey: persistKey) }

    /// Éléments épinglés : toujours en tête, jamais supprimés par les nouvelles copies.
    private(set) var pinned: [String] = []
    /// Copies récentes (hors épinglés).
    private(set) var recent: [String] = []
    /// Images récentes.
    private(set) var images: [ClipImage] = []
    /// Vue d'ensemble des textes (épinglés puis récents), utilisée par l'intégration AlyNotch.
    var items: [String] { pinned + recent }

    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let maxItems = 30
    private let maxImages = 10
    /// Au-delà, une image n'est pas gardée (mémoire et disque).
    private let maxImageBytes = 8_000_000
    /// Appelé quand la liste change (utilisé par l'intégration AlyNotch).
    var onChange: (() -> Void)?

    private let pinsURL: URL
    private let vaultURL: URL
    private var saveWork: DispatchWorkItem?

    /// Marqueurs posés par les gestionnaires de mots de passe (convention nspasteboard.org).
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    private struct Stored: Codable {
        var recent: [String]
        var images: [Data]
    }

    /// `directory` : dossier des fichiers (par défaut ~/Library/Application Support/Copiste).
    init(directory: URL? = nil) {
        let dir = directory ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Copiste", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        pinsURL = dir.appendingPathComponent("pins.json")
        vaultURL = dir.appendingPathComponent("history.enc")
        if let data = try? Data(contentsOf: pinsURL),
           let saved = try? JSONDecoder().decode([String].self, from: data) {
            pinned = saved
        }
        if Self.persistEnabled { loadVault() }
    }

    /// Données fictives pour l'export des visuels (--snapshot).
    func loadDemo(pinned: [String], recent: [String]) {
        self.pinned = pinned
        self.recent = recent
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.poll()
        }
    }

    /// À appeler après avoir écrit nous-mêmes dans le presse-papier.
    func ignoreCurrent() {
        lastChange = NSPasteboard.general.changeCount
    }

    /// Vide les copies récentes et les images ; les éléments épinglés sont conservés.
    func clear() {
        recent.removeAll()
        images.removeAll()
        changed()
    }

    func pin(_ text: String) {
        recent.removeAll { $0 == text }
        if !pinned.contains(text) { pinned.append(text) }
        savePins()
        changed()
    }

    func unpin(_ text: String) {
        guard pinned.contains(text) else { return }
        pinned.removeAll { $0 == text }
        recent.insert(text, at: 0)
        trim()
        savePins()
        changed()
    }

    /// Supprime un élément, épinglé ou non.
    func remove(_ text: String) {
        let wasPinned = pinned.contains(text)
        pinned.removeAll { $0 == text }
        recent.removeAll { $0 == text }
        if wasPinned { savePins() }
        changed()
    }

    func removeImage(_ id: UUID) {
        images.removeAll { $0.id == id }
        changed()
    }

    // MARK: - Persistance (option)

    /// Active ou coupe la conservation chiffrée. En la coupant, le fichier et la clé sont supprimés.
    func setPersistence(_ on: Bool) {
        UserDefaults.standard.set(on, forKey: Self.persistKey)
        if on {
            saveVaultNow()
        } else {
            saveWork?.cancel()
            try? FileManager.default.removeItem(at: vaultURL)
            HistoryVault.deleteKey()
        }
    }

    private func loadVault() {
        guard let sealed = try? Data(contentsOf: vaultURL),
              let plain = HistoryVault.open(sealed),
              let stored = try? JSONDecoder().decode(Stored.self, from: plain) else { return }
        recent = stored.recent.filter { !pinned.contains($0) }
        images = stored.images.map { ClipImage(png: $0) }
    }

    private func saveVaultNow() {
        guard Self.persistEnabled else { return }
        let stored = Stored(recent: recent, images: images.map(\.png))
        guard let plain = try? JSONEncoder().encode(stored), let sealed = HistoryVault.seal(plain) else { return }
        try? sealed.write(to: vaultURL, options: [.atomic, .completeFileProtection])
    }

    /// Regroupe les écritures : une seule sauvegarde 1,5 s après le dernier changement.
    private func scheduleSave() {
        guard Self.persistEnabled else { return }
        saveWork?.cancel()
        let work = DispatchWorkItem { [weak self] in self?.saveVaultNow() }
        saveWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.5, execute: work)
    }

    private func changed() {
        scheduleSave()
        onChange?()
    }

    // MARK: - Interne

    private func trim() {
        if recent.count > maxItems { recent.removeLast(recent.count - maxItems) }
    }

    private func savePins() {
        if let data = try? JSONEncoder().encode(pinned) {
            try? data.write(to: pinsURL, options: .atomic)
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount

        if let types = pb.types, types.contains(where: { ignoredTypes.contains($0.rawValue) }) { return }

        // Le texte prime : une copie qui contient du texte et une image (page web) reste du texte.
        if let text = pb.string(forType: .string) {
            guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
            // Déjà épinglé : on ne le duplique pas dans les récents.
            guard !pinned.contains(text) else { return }
            recent.removeAll { $0 == text }
            recent.insert(text, at: 0)
            trim()
            changed()
            return
        }

        if let png = Self.pngData(from: pb), png.count <= maxImageBytes {
            images.removeAll { $0.png == png }
            images.insert(ClipImage(png: png), at: 0)
            if images.count > maxImages { images.removeLast(images.count - maxImages) }
            changed()
        }
    }

    /// Image du presse-papier en PNG (les captures arrivent en PNG ou en TIFF).
    private static func pngData(from pb: NSPasteboard) -> Data? {
        if let png = pb.data(forType: .png) { return png }
        if let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) {
            return rep.representation(using: .png, properties: [:])
        }
        return nil
    }
}
