import AppKit

/// Historique texte du presse-papier, en mémoire uniquement.
/// Seuls les éléments épinglés par l'utilisateur sont enregistrés sur disque
/// (~/Library/Application Support/Copiste/pins.json).
/// macOS ne notifie pas les changements : on compare `changeCount` toutes les 0,5 s.
final class ClipboardHistory {
    /// Éléments épinglés : toujours en tête, jamais supprimés par les nouvelles copies.
    private(set) var pinned: [String] = []
    /// Copies récentes (hors épinglés).
    private(set) var recent: [String] = []
    /// Vue d'ensemble (épinglés puis récents), utilisée par l'intégration AlyNotch.
    var items: [String] { pinned + recent }

    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let maxItems = 30
    /// Appelé quand la liste change (utilisé par l'intégration AlyNotch).
    var onChange: (() -> Void)?

    private let pinsURL: URL = {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Copiste", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir.appendingPathComponent("pins.json")
    }()

    /// Marqueurs posés par les gestionnaires de mots de passe (convention nspasteboard.org).
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    init() {
        if let data = try? Data(contentsOf: pinsURL),
           let saved = try? JSONDecoder().decode([String].self, from: data) {
            pinned = saved
        }
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.poll()
        }
    }

    /// À appeler après avoir écrit nous-mêmes dans le presse-papier.
    func ignoreCurrent() {
        lastChange = NSPasteboard.general.changeCount
    }

    /// Vide les copies récentes ; les éléments épinglés sont conservés.
    func clear() {
        recent.removeAll()
        onChange?()
    }

    func pin(_ text: String) {
        recent.removeAll { $0 == text }
        if !pinned.contains(text) { pinned.append(text) }
        savePins()
        onChange?()
    }

    func unpin(_ text: String) {
        guard pinned.contains(text) else { return }
        pinned.removeAll { $0 == text }
        recent.insert(text, at: 0)
        trim()
        savePins()
        onChange?()
    }

    /// Supprime un élément, épinglé ou non.
    func remove(_ text: String) {
        let wasPinned = pinned.contains(text)
        pinned.removeAll { $0 == text }
        recent.removeAll { $0 == text }
        if wasPinned { savePins() }
        onChange?()
    }

    private func trim() {
        if recent.count > maxItems { recent.removeLast(recent.count - maxItems) }
    }

    private func savePins() {
        if let data = try? JSONEncoder().encode(pinned) {
            try? data.write(to: pinsURL, options: .atomic)
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount

        if let types = pb.types, types.contains(where: { ignoredTypes.contains($0.rawValue) }) { return }
        guard let text = pb.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        // Déjà épinglé : on ne le duplique pas dans les récents.
        guard !pinned.contains(text) else { return }
        recent.removeAll { $0 == text }
        recent.insert(text, at: 0)
        trim()
        onChange?()
    }
}
