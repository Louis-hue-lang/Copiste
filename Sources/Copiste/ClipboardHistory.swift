import AppKit

/// Historique texte du presse-papier, en mémoire uniquement.
/// macOS ne notifie pas les changements : on compare `changeCount` toutes les 0,5 s.
final class ClipboardHistory {
    private(set) var items: [String] = []
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let maxItems = 30

    /// Marqueurs posés par les gestionnaires de mots de passe (convention nspasteboard.org).
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.poll()
        }
    }

    /// À appeler après avoir écrit nous-mêmes dans le presse-papier.
    func ignoreCurrent() {
        lastChange = NSPasteboard.general.changeCount
    }

    func clear() {
        items.removeAll()
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount

        if let types = pb.types, types.contains(where: { ignoredTypes.contains($0.rawValue) }) { return }
        guard let text = pb.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        items.removeAll { $0 == text }
        items.insert(text, at: 0)
        if items.count > maxItems { items.removeLast(items.count - maxItems) }
    }
}
